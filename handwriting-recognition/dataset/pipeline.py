"""Deterministic dataset manifest and data-quality report generator.

Run from the repository root via ``scripts/build_data_manifests.py``. This
module never downloads data, trains a model, or modifies source datasets.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from config import get_path, load_config
from dataset.iam import SplitUnavailableError, build_iam_manifests
from dataset.idx import IdxSplitReport, mnist_manifest_records, validate_idx_split
from dataset.manifest import GENERATOR_VERSION, config_digest, write_manifest

MNIST_FILES = {
    "train": ("train-images.idx3-ubyte", "train-labels.idx1-ubyte"),
    "test": ("t10k-images.idx3-ubyte", "t10k-labels.idx1-ubyte"),
}
IAM_SPLITS = ("train", "val", "test")


def _mnist_meta(report: IdxSplitReport, config_hash: str) -> dict[str, Any]:
    return {
        "generator_version": GENERATOR_VERSION,
        "config_sha256": config_hash,
        "dataset": "mnist",
        "split": report.name,
        "source_image": report.image_path.name,
        "source_image_sha256": report.image_sha256,
        "source_label": report.label_path.name,
        "source_label_sha256": report.label_sha256,
        "image_count": report.image_count,
        "label_count": report.label_count,
        "rows": report.rows,
        "cols": report.cols,
        "integrity_ok": report.ok,
        "issues": list(report.issues),
    }


def _render_report(
    mnist_reports: dict[str, IdxSplitReport],
    iam_status: str,
    iam_stats: dict[str, Any],
    iam_issues: list[str],
    manifest_paths: list[Path],
    root: Path,
) -> str:
    lines: list[str] = [
        "# Pen2Pixel — Data Quality Report",
        "",
        "Generated by the deterministic Milestone 3 pipeline. No timestamps are included so "
        "repeated runs on unchanged inputs produce identical reports. No dataset was downloaded "
        "and no model was trained.",
        "",
        "## 1. MNIST",
        "",
        "Source: local IDX files under `handwriting-recognition/dataset/mnist/` (gitignored, "
        "verified in Milestone 0). Both train and test splits are present and separately stored.",
        "",
    ]
    for name, report in mnist_reports.items():
        lines.extend(
            [
                f"### {name}",
                "",
                f"- Images: `{report.image_path.relative_to(root).as_posix()}` "
                f"(SHA-256 `{report.image_sha256}`)",
                f"- Labels: `{report.label_path.relative_to(root).as_posix()}` "
                f"(SHA-256 `{report.label_sha256}`)",
                f"- Image count: {report.image_count}; label count: {report.label_count}",
                f"- Dimensions: {report.rows} x {report.cols} pixels; pixel type: unsigned byte (IDX code 0x08)",
                f"- Label range: {report.label_min}..{report.label_max}; "
                f"classes present: {list(report.unique_labels)}",
                f"- Pixel statistics: min={report.pixel_min}, max={report.pixel_max}, "
                f"mean={report.pixel_mean:.4f}, std={report.pixel_std:.4f}",
                f"- Integrity: {'PASS' if report.ok else 'EXCEPTIONS: ' + '; '.join(report.issues)}",
                "",
                "| Label | Count |",
                "|---:|---:|",
            ]
        )
        for label, count in enumerate(report.label_histogram):
            lines.append(f"| {label} | {count} |")
        lines.append("")

    lines.extend(
        [
            "## 2. IAM Handwriting Database",
            "",
            f"Status: **{iam_status}**.",
            "",
        ]
    )
    if iam_status.startswith("BLOCKED"):
        lines.extend(
            [
                "The official IAM data and/or writer-independent partition files are not present "
                "locally, so **no IAM statistics are reported and no split was invented**. "
                "See `docs/IAM_ACQUISITION.md` for the source, licensing checklist and expected layout.",
                "",
                "Reason(s):",
                "",
            ]
        )
        lines.extend(f"- {issue}" for issue in iam_issues)
        lines.append("")
    else:
        lines.extend(
            [
                f"- Lines: {iam_stats.get('line_count', 0)}; forms: {iam_stats.get('form_count', 0)}; "
                f"words: {iam_stats.get('word_count', 0)}; writers: {iam_stats.get('writer_count', 0)}",
                f"- Writers per split: {iam_stats.get('writers_by_split', {})}",
                f"- Text length: {iam_stats.get('text_lengths', {})}",
                f"- Image dimensions: {iam_stats.get('dimension_counts', {})}",
                f"- Unusable line records: {iam_stats.get('unusable_records', 0)}",
                "",
                "Validation issues (never silently discarded):",
                "",
            ]
        )
        lines.extend(f"- {issue}" for issue in iam_issues[:200])
        if len(iam_issues) > 200:
            lines.append(f"- ... and {len(iam_issues) - 200} more (see manifests).")
        lines.append("")

    lines.extend(
        [
            "## 3. Manifests",
            "",
            "Manifests are deterministic JSONL files: a `meta` record followed by one record per "
            "sample. They contain paths, labels/transcriptions and metadata only — no image bytes "
            "are duplicated.",
            "",
        ]
    )
    for path in manifest_paths:
        lines.append(f"- `{path.relative_to(root).as_posix()}`")
    lines.extend(
        [
            "",
            "## 4. Validation Rules",
            "",
            "- MNIST: IDX magic numbers, data type code, header dimensions, exact file byte lengths, "
            "image/label count equality, label range, expected 28x28 geometry, split separation.",
            "- IAM: official annotation hierarchy (forms → lines → words), writer identifiers, "
            "official writer-independent partition membership, writer disjointness across splits, "
            "missing images, invalid images, empty transcriptions, duplicate ids/content, "
            "unexpected dimensions and unusable samples.",
            "- Invalid samples are recorded with `usable: false` and an issue list; none is silently removed.",
            "",
            "## 5. Limitations",
            "",
            "- IAM is absent in this environment; its real statistics cannot be reported without fabrication.",
            "- Bounding-box level word segmentation is parsed but not used by the text-line baseline.",
            "- Duplicate-content detection uses image SHA-256 and is therefore exact-byte only.",
            "- No performance or accuracy figures are reported; no model has been trained.",
            "",
        ]
    )
    return "\n".join(lines)


def build(config_path: Path | None = None) -> dict[str, Any]:
    """Build all manifests and the data quality report.

    Returns a summary dictionary with counts and paths.
    """
    config = load_config(config_path)
    resolved_config = config_path or Path(__import__("os").environ.get("PEN2PIXEL_CONFIG", "configs/default.yaml"))
    if not resolved_config.is_absolute():
        resolved_config = (Path(__file__).resolve().parents[2] / resolved_config)
    config_hash = config_digest(resolved_config)
    root = Path(__file__).resolve().parents[2]

    manifest_dir = get_path(config, "dataset.manifest_dir")
    report_path = get_path(config, "dataset.report_path")
    mnist_cfg = config["dataset"]["mnist"]
    mnist_dir = get_path(config, "paths.mnist_dir")

    mnist_reports: dict[str, IdxSplitReport] = {}
    manifest_paths: list[Path] = []
    for split_name, (image_name, label_name) in MNIST_FILES.items():
        report = validate_idx_split(
            mnist_dir / image_name,
            mnist_dir / label_name,
            int(mnist_cfg["expected_rows"]),
            int(mnist_cfg["expected_cols"]),
            int(mnist_cfg["expected_label_classes"]),
            split_name,
        )
        mnist_reports[split_name] = report
        records = mnist_manifest_records(report, root)
        manifest_paths.append(
            write_manifest(manifest_dir / f"mnist_{split_name}.jsonl", _mnist_meta(report, config_hash), records)
        )

    iam_root = get_path(config, "paths.iam_dir")
    iam_cfg = config["dataset"]["iam"]
    iam_status = "BLOCKED — official source data not present"
    iam_stats: dict[str, Any] = {}
    iam_issues: list[str] = []
    try:
        records_by_split, iam_stats, iam_issues = build_iam_manifests(
            iam_root,
            iam_cfg["split"],
            iam_cfg["annotations"],
            iam_cfg["lines_subdir"],
            bool(iam_cfg["hash_images"]),
        )
        iam_status = "AVAILABLE — official annotations parsed"
        for split_name in IAM_SPLITS:
            meta = {
                "generator_version": GENERATOR_VERSION,
                "config_sha256": config_hash,
                "dataset": "iam",
                "split": split_name,
                "source": iam_root.relative_to(root).as_posix() if iam_root.is_relative_to(root) else str(iam_root),
                "record_count": len(records_by_split[split_name]),
                "integrity_ok": not any("multiple splits" in issue or "overlap" in issue for issue in iam_issues),
            }
            manifest_paths.append(
                write_manifest(manifest_dir / f"iam_{split_name}.jsonl", meta, records_by_split[split_name])
            )
    except (SplitUnavailableError, FileNotFoundError, KeyError) as exc:
        reason = str(exc).replace(str(root), ".")
        iam_issues = [reason]
        for split_name in IAM_SPLITS:
            meta = {
                "generator_version": GENERATOR_VERSION,
                "config_sha256": config_hash,
                "dataset": "iam",
                "split": split_name,
                "status": "blocked_source_unavailable",
                "reason": reason,
                "record_count": 0,
            }
            manifest_paths.append(write_manifest(manifest_dir / f"iam_{split_name}.jsonl", meta, []))

    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(
        _render_report(mnist_reports, iam_status, iam_stats, iam_issues, manifest_paths, root),
        encoding="utf-8",
    )

    return {
        "config_sha256": config_hash,
        "mnist": {name: report.image_count for name, report in mnist_reports.items()},
        "mnist_ok": all(report.ok for report in mnist_reports.values()),
        "iam_status": iam_status,
        "manifests": [path.relative_to(root).as_posix() for path in manifest_paths],
        "report": report_path.relative_to(root).as_posix(),
    }


if __name__ == "__main__":
    result = build()
    for key, value in result.items():
        print(f"{key}: {value}")
